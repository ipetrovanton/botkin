"""Ключевые слова и утилиты для классификации документов."""

import re

# Заголовки колонок, специфичные для лабораторных бланков
LAB_TABLE_MARKERS = ("референс", "ед. изм", "ед.изм", "единиц измер")

# Ключевые слова, указывающие на неизвестный тип документа
UNKNOWN_TITLE_KEYWORDS = ("рецепт", "назначение", "препарат")

# Ключевые слова для заключений врача
