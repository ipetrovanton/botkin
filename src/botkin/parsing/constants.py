"""Общие регулярные выражения и токены для парсинга лабораторных бланков."""

import re

# Диапазон референса: "35 - 45", "35–45", "35—45"
RANGE_RE = re.compile(r"^(-?\d+(?:[.,]\d+)?)\s*[-–—]\s*(-?\d+(?:[.,]\d+)?)$")
# Верхняя граница: "< 1.0", "≤ 1.0"
LE_RE = re.compile(r"^[<≤]\s*(-?\d+(?:[.,]\d+)?)$")
# Нижняя граница: "> 120", "≥ 120"
GE_RE = re.compile(r"^[>≥]\s*(-?\d+(?:[.,]\d+)?)$")
# Любое число (не ловим дефис между цифрами как знак отрицания)
NUM_RE = re.compile(r"(?<![\d.,])-?\d+(?:[.,]\d+)?")

# Поиск диапазона в свободном тексте (без привязки к началу строки)
RANGE_SEARCH_RE = re.compile(r"(\d+(?:[.,]\d+)?)\s*[-–—]\s*(\d+(?:[.,]\d+)?)")
UPPER_SEARCH_RE = re.compile(r"[<≤]\s*(\d+(?:[.,]\d+)?)")
LOWER_SEARCH_RE = re.compile(r"[>≥]\s*(\d+(?:[.,]\d+)?)")

# Маркеры СИБР-теста в тексте
SIBR_MARKERS = ("сибр", "водородно-метановый", "дыхательный тест", "lactulose", "лактулоза")
# Газовые показатели (H2, CH4, O2) — достаточно специфичный паттерн
GAS_MARKERS = ("h2", "ch4", "o2")

# Названия газов в выходном имени показателя
GAS_NAME = {
    "h2": ("водород H2", "ppm"),
    "ch4": ("метан CH4", "ppm"),
    "h2_2ch4": ("H2 + 2CH4", "ppm"),
    "o2": ("кислород O2", "% КВМ"),
}

# Регулярное выражение для построчного разбора СИБР
SIBR_ROW_RE = re.compile(
    r"^(?P<time>\d+)\s*мин\s*:?\s*"
    r"H2\s*=\s*(?P<h2>\d+(?:[.,]\d+)?)\*?\s*(?:ppm)?\s*[,;]?\s*"
    r"CH4\s*=\s*(?P<ch4>\d+(?:[.,]\d+)?)\*?\s*(?:ppm)?\s*[,;]?\s*"
    r"H2\+2CH4\s*=\s*(?P<h2_2ch4>\d+(?:[.,]\d+)?)\*?\s*(?:ppm)?\s*[,;]?\s*"
    r"O2\s*=\s*(?P<o2>\d+(?:[.,]\d+)?)\*?\s*%?",
    re.IGNORECASE | re.UNICODE,
)
