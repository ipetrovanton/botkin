"""P2: кластеризация слов в строки по скользящему центроиду, а не по анкеру.

Баг анкерной кластеризации: каждое слово сравнивается с y0 ПЕРВОГО слова кластера.
При плавном вертикальном дрейфе строки (каждое слово чуть ниже предыдущего, в пределах
толеранции от соседа) накопленное смещение от анкера превышает y_tol → строка рвётся,
хотя соседние слова почти на одной высоте. Скользящий центроид (среднее y0 кластера)
следует за дрейфом.
"""
from botkin.preprocess.pdf_text import _page_lines


class _FakePage:
    def __init__(self, words):
        self._words = words

    def get_text(self, kind):
        assert kind == "words"
        return self._words


def test_gradual_y_drift_stays_one_line():
    # y0: 100 → 102 → 104. Соседи в пределах tol=3, но 104-100=4 > tol (анкер бы порвал).
    words = [
        (0, 100, 10, 110, "Гемоглобин", 0, 0, 0),
        (20, 102, 30, 112, "140", 0, 0, 1),
        (40, 104, 50, 114, "г/л", 0, 0, 2),
    ]
    lines = _page_lines(_FakePage(words), y_tol=3.0)
    assert lines == ["Гемоглобин 140 г/л"]


def test_distinct_rows_still_split():
    # Настоящий разрыв строк (большой зазор по Y) должен сохраниться.
    words = [
        (0, 100, 10, 110, "Гемоглобин", 0, 0, 0),
        (20, 101, 30, 111, "140", 0, 0, 1),
        (0, 130, 10, 140, "Эритроциты", 0, 1, 0),
        (20, 131, 30, 141, "4.5", 0, 1, 1),
    ]
    lines = _page_lines(_FakePage(words), y_tol=3.0)
    assert lines == ["Гемоглобин 140", "Эритроциты 4.5"]
